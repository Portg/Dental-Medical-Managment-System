    public function run(): void
    {
        $owner = User::orderBy('id')->value('id');

        if (!$owner) {
            $this->command?->warn('[ClinicalPhraseLibrary] 库里还没有用户，跳过。');
            return;
        }

        $inserted = 0;
        $updated  = 0;

        foreach ($this->library() as $category => $slots) {
            foreach ($slots as $slot => $phrases) {
                foreach (array_values($phrases) as $i => $phrase) {
                    $existing = QuickPhrase::where('category', $category)
                        ->where('phrase', $phrase)
                        ->first();

                    if ($existing) {
                        $existing->update(['slot' => $slot, 'sort_order' => $i, 'is_active' => true]);
                        $updated++;
                        continue;
                    }

                    QuickPhrase::create([
                        // shortcut 是 ; 选择器认的简写。临床短语多为中文且量大，
                        // 逐条编简写既没人记得住也容易撞；留空，靠 ; 之后直接打中文筛。
                        'shortcut'   => '',
                        'phrase'     => $phrase,
                        'category'   => $category,
                        'slot'       => $slot,
                        'sort_order' => $i,
                        'scope'      => 'system',
                        'is_active'  => true,
                        '_who_added' => $owner,
                    ]);
                    $inserted++;
                }
            }
        }

        $this->command?->info("[ClinicalPhraseLibrary] 新增 {$inserted} 条，更新 {$updated} 条。");
    }

