/**
 * 口腔临床短语库初版。
 *
 * 结构来自参考产品的操作录像：短语按**句子的语义槽位**分组，不是按「检查/诊断/治疗」
 * 三个大类平铺。现病史那一栏的槽位是「时间 → 部位 → 症状 → 治疗情况 → 症状变化 →
 * 口腔习惯」—— 那正是一句现病史的句子结构，医生顺着点下来自然成句。
 *
 * 两条硬约定，整库统一：
 *
 *   标点在短语里。「本院治疗，」「未治疗。」连点两条不会粘在一起。
 *                  句中项带逗号，句末项带句号，纯名词（牙石、软垢）不带。
 *   {} 是光标位。  「PD={}mm，」插入后光标落在 {} 处，医生只补数值。
 *                  不用 __ —— 那个在病历模板里表示「替换成本行牙位」。
 *
 * 视频只完整展示了现病史与检查两栏。其余各栏（主诉 / 既往史 / 辅助检查 / 诊断 /
 * 治疗计划 / 治疗 / 医嘱）按同一套槽位思路补全，覆盖牙体牙髓、牙周、外科、修复、
 * 儿牙、正畸六个方向 —— 这是初版，医生用起来一定要改，「快捷短语」管理页能改。
 *
 * 幂等：按 (category, phrase) upsert，重复执行不会翻倍。
 */
class ClinicalPhraseLibrarySeeder extends Seeder
